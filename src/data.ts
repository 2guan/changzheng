export function project(point: [number, number]): [number, number] {
  return [(point[0] - 98) * 51 + 35, (38 - point[1]) * 40 + 20];
}
export function routePath(points: [number, number][]) {
  return points
    .map((p, i) => `${i ? "L" : "M"} ${project(p).join(" ")}`)
    .join(" ");
}
