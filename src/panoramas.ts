export type PanoramaProgress = { lastStation: number; seen: number[] };
export function sanitizePanoramaProgress(raw: unknown): PanoramaProgress {
  const fallback = { lastStation: 1, seen: [] };
  if (!raw || typeof raw !== "object") return fallback;
  const r = raw as Record<string, unknown>;
  const valid = (x: unknown): x is number =>
    typeof x === "number" && Number.isInteger(x) && x >= 1 && x <= 22;
  return {
    lastStation: valid(r.lastStation) ? r.lastStation : 1,
    seen: Array.isArray(r.seen) ? [...new Set(r.seen.filter(valid))] : [],
  };
}
export function panoramaStation(raw: string | null, fallback = 1) {
  const id = Number(raw);
  return raw !== null && Number.isInteger(id) && id >= 1 && id <= 22
    ? id
    : fallback;
}
